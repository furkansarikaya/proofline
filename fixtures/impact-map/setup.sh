# stock

Warehouse stock reservation. `reserveStock(sku, qty)` holds units for an order.
EOF

cat > src/stock/reserve.js <<'EOF'
const held = new Map();

// Holds qty units of sku. Returns the new held total.
export function reserveStock(sku, qty) {
  const next = (held.get(sku) ?? 0) + qty;
  held.set(sku, next);
  return next;
}

export function releaseStock(sku, qty) {
  const next = Math.max(0, (held.get(sku) ?? 0) - qty);
  held.set(sku, next);
  return next;
}
EOF

