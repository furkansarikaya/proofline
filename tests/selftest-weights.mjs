// @ts-check
// Regenerates tests/selftest-weights.txt from measured unit times.
//   node tests/selftest-weights.mjs [-o FILE] [--note TEXT]... TIMES_FILE_OR_DIR...
// A times file holds one line per unit, "<seconds> <suite> [scenario]", as SELFTEST_TIMES_FILE=<file> node tests/selftest.mjs
// appends them (CI uploads one per shard). A directory argument stands for every regular file below it (the
// downloaded artifacts). A unit that appears in several files (several runs) gets the average of its seconds; units are
// written longest first. -o defaults to tests/selftest-weights.txt next to this script; --note adds a header line.
// Exit 2 on a bad argument or a malformed line (the message names file and line); nothing is written then.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const here = import.meta.dirname;
class Usage extends Error {}

/** @param {string} d @returns {string[]} every regular file below d, in byte order */
function filesBelow(d) {
  /** @type {string[]} */ const out = [];
  for (const n of readdirSync(d).sort()) {
    const f = path.join(d, n);
    const st = statSync(f);
    if (st.isDirectory()) out.push(...filesBelow(f)); else if (st.isFile()) out.push(f);
  }
  return out;
}
/** Byte-order comparison (the C locale `sort`). @param {string} a @param {string} b */
const byBytes = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * The weights file text for the times files.
 * @param {{ inputs: string[], notes?: string[] }} o
 * @returns {string}
 */
export function weightsText({ inputs, notes = [] }) {
  /** @type {string[]} */ const files = [];
  for (const a of inputs) {
    if (existsSync(a) && statSync(a).isDirectory()) files.push(...filesBelow(a));
    else if (existsSync(a) && statSync(a).isFile()) files.push(a);
    else throw new Usage(`selftest-weights: no such file or directory: ${a}`);
  }
  if (files.length === 0) throw new Usage('selftest-weights: no times file found');
  /** @type {Map<string, { sum: number, n: number }>} */ const acc = new Map();
  for (const f of files) {
    const lines = readFileSync(f, 'utf8').split('\n');
    if (lines.at(-1) === '') lines.pop();
    lines.forEach((line, i) => {
      if (/^\s*(#|$)/.test(line)) return;
      const w = line.trim().split(/\s+/);
      if (!/^[0-9]+$/.test(w[0]) || w.length < 2 || w.length > 4 || !/^[A-Za-z0-9_.-]+$/.test(w[1])) throw new Usage(`selftest-weights: ${f}:${i + 1}: not "<seconds> <suite> [scenario]": ${line}`);
      const key = w.slice(1).join(' ');
      const e = acc.get(key) ?? { sum: 0, n: 0 };
      e.sum += Number(w[0]); e.n++; acc.set(key, e);
    });
  }
  if (acc.size === 0) throw new Usage('selftest-weights: the times files hold no unit');
  const rows = [...acc].map(([k, { sum, n }]) => ({ w: Math.max(1, Math.floor(sum / n + 0.5)), k }));
  rows.sort((a, b) => b.w - a.w || byBytes(a.k, b.k));
  return [
    '# Unit weights for tests/selftest.mjs (A109): "<seconds> <suite> [scenario]", longest first.',
    `# Generated by tests/selftest-weights.mjs from ${files.length} times file(s), ${rows.length} units; a unit seen in several files weighs the`,
    '# average of its seconds. Seconds are as measured under a 4-core CI shard; only the ratios matter.',
    '# A unit that is not listed weighs the MEDIAN of the listed units. Shards are filled longest unit first onto the',
    '# lightest shard; a stale weight only costs balance, it never drops or loosens a test.',
    '# Refresh: download the selftest-times artifacts of a CI run, then node tests/selftest-weights.mjs <dir>.',
    ...notes.map((n) => `# ${n}`),
    ...rows.map((r) => `${r.w} ${r.k}`),
  ].join('\n') + '\n';
}

/** @param {string[]} argv @returns {number} the exit status */
export function main(argv) {
  let out = path.join(here, 'selftest-weights.txt');
  /** @type {string[]} */ const notes = []; /** @type {string[]} */ const inputs = [];
  try {
    for (let i = 0; i < argv.length; i++) {
      const a = argv[i];
      if (a === '-o') { if (i + 1 >= argv.length) throw new Usage('selftest-weights: -o needs a file'); out = argv[++i]; }
      else if (a === '--note') { if (i + 1 >= argv.length) throw new Usage('selftest-weights: --note needs a text'); notes.push(argv[++i]); }
      else if (a.startsWith('-')) throw new Usage(`selftest-weights: unknown option ${a}`);
      else inputs.push(a);
    }
    if (inputs.length === 0) throw new Usage('usage: selftest-weights.mjs [-o FILE] [--note TEXT]... TIMES_FILE_OR_DIR...');
    writeFileSync(out, weightsText({ inputs, notes }));
    return 0;
  } catch (e) {
    if (e instanceof Usage) { console.error(e.message); return 2; }
    throw e;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main(process.argv.slice(2));
