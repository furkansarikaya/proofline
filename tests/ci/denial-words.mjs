// @ts-check
// A363 (C8a): the words a denial class of `tools.jsonl` may hold are the words of the hook's own prose, never a word a model typed. This script derives the list from the string
// literals of the Node hook (adapters/claude/hooks: the deny reasons and the message constants of the guards) and writes control-plane/agents/scripts/core/denialwords.mjs.
//   node tests/ci/denial-words.mjs           write the file
//   node tests/ci/denial-words.mjs --check   exit 1 when the file differs (a hook text changed: regenerate and read the diff)
// A string literal counts when it has at least four blanks (a sentence, not an identifier or a pattern) and no backslash; its words are the plain
// lower-case words ([a-z]+ with inner hyphens) of the text with the `${...}` parts removed, so a path, an identifier or a value the hook echoes is never in the list.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const hooks = path.join(root, 'adapters/claude/hooks');
const out = path.join(root, 'control-plane/agents/scripts/core/denialwords.mjs');

/** The text tools tests/ci/no-shell-logic.mjs (TEXT_PROGRAMS) refuses to see named as a string: a denial that mentions one simply loses that word in its class. */
const TEXT_TOOLS = new Set(['awk', 'gawk', 'mawk', 'nawk', 'sed', 'gsed']);

/** @param {string} d @returns {string[]} */
function files(d) {
  /** @type {string[]} */ const r = [];
  for (const e of readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) r.push(...files(p)); else if (e.name.endsWith('.mjs')) r.push(p);
  }
  return r.sort();
}

/** The string literals of a source text (single, double and template quotes; a template's `${...}` parts are dropped). @param {string} src @returns {string[]} */
export function literals(src) {
  /** @type {string[]} */ const lits = [];
  const re = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"|`((?:[^`\\]|\\.)*)`/g;
  for (let m = re.exec(src); m !== null; m = re.exec(src)) {
    const t = (m[1] ?? m[2] ?? m[3] ?? '').replace(/\$\{[^}]*\}/g, ' ');
    if ((t.match(/ /g) ?? []).length >= 4 && !/\\/.test(t)) lits.push(t);
  }
  return lits;
}

/** @returns {string[]} the sorted word list */
export function derive() {
  /** @type {Set<string>} */ const words = new Set();
  for (const f of files(hooks)) for (const t of literals(readFileSync(f, 'utf8'))) for (const w of t.split(/[^A-Za-z-]+/)) if (/^[a-z]+(?:-[a-z]+)*$/.test(w) && !TEXT_TOOLS.has(w)) words.add(w);
  return [...words].sort();
}

/** @param {string[]} list */
export function render(list) {
  /** @type {string[]} */ const rows = [];
  let cur = '';
  for (const w of list) { const q = `'${w}',`; if (cur.length + q.length + 1 > 150) { rows.push(cur); cur = q; } else cur = cur === '' ? q : `${cur} ${q}`; }
  if (cur !== '') rows.push(cur);
  return `// @ts-check\n// GENERATED by tests/ci/denial-words.mjs from the string literals of adapters/claude/hooks (A363, C8a); do not edit by hand.\n// The words a denial class of tools.jsonl may keep: the hook's own prose.\nexport const DENIAL_WORDS = new Set([\n${rows.map((r) => `  ${r}`).join('\n')}\n]);\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  const text = render(derive());
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { process.stderr.write('denialwords.mjs is not in sync with the hook text: node tests/ci/denial-words.mjs\n'); process.exit(1); }
    process.stdout.write('denial words in sync\n');
  } else { writeFileSync(out, text); process.stdout.write(`wrote ${out}\n`); }
}
