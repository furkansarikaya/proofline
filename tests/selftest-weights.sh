#!/bin/sh
# Regenerates tests/selftest-weights.txt from measured unit times.
#   sh tests/selftest-weights.sh [-o FILE] [--note TEXT]... TIMES_FILE_OR_DIR...
# A times file holds one line per unit, "<seconds> <suite> [scenario]", as SELFTEST_TIMES_FILE=<file> sh tests/selftest.sh
# appends them (CI uploads one per shard). A directory argument stands for every regular file below it (the
# downloaded artifacts). A unit that appears in several files (several runs) gets the average of its seconds; units are
# written longest first. -o defaults to tests/selftest-weights.txt next to this script; --note adds a header line.
# Exit 2 on a bad argument or a malformed line (the message names file and line); nothing is written then.
set -u
here=$(CDPATH='' cd "$(dirname "$0")" && pwd)
out=$here/selftest-weights.txt
notes=''
inputs=''
while [ $# -gt 0 ]; do
  case "$1" in
    -o) [ $# -ge 2 ] || { echo "selftest-weights: -o needs a file" >&2; exit 2; }; out=$2; shift 2 ;;
    --note) [ $# -ge 2 ] || { echo "selftest-weights: --note needs a text" >&2; exit 2; }
            notes="$notes
# $2"; shift 2 ;;
    -*) echo "selftest-weights: unknown option $1" >&2; exit 2 ;;
    *) inputs="$inputs
$1"; shift ;;
  esac
done
[ -n "$inputs" ] || { echo "usage: selftest-weights.sh [-o FILE] [--note TEXT]... TIMES_FILE_OR_DIR..." >&2; exit 2; }

tmp=$(mktemp "${TMPDIR:-/tmp}/proofline-weights.XXXXXX") || exit 2
trap 'rm -f "$tmp" "$tmp.out"' EXIT
nfiles=0
files=$(printf '%s\n' "$inputs" | sed '/^$/d' | while IFS= read -r a; do
  if [ -d "$a" ]; then find "$a" -type f | LC_ALL=C sort
  elif [ -f "$a" ]; then printf '%s\n' "$a"
  else echo "selftest-weights: no such file or directory: $a" >&2; echo "!bad"; fi
done)
case "$files" in *'!bad'*) exit 2 ;; esac
[ -n "$files" ] || { echo "selftest-weights: no times file found" >&2; exit 2; }
printf '%s\n' "$files" | while IFS= read -r f; do
  # a valid line: whole seconds, a suite name, an optional scenario; blank lines and # comments are skipped
  awk -v f="$f" '
    /^[[:space:]]*(#|$)/ { next }
    $1 !~ /^[0-9]+$/ || NF < 2 || NF > 4 || $2 !~ /^[A-Za-z0-9_.-]+$/ { printf "selftest-weights: %s:%d: not \"<seconds> <suite> [scenario]\": %s\n", f, FNR, $0 > "/dev/stderr"; bad = 1; exit }
    { sub(/^[[:space:]]+/, ""); print "T", $0 }
    END { exit bad }' "$f" >> "$tmp" || exit 2
done || exit 2
nfiles=$(printf '%s\n' "$files" | wc -l | tr -d ' ')
[ -s "$tmp" ] || { echo "selftest-weights: the times files hold no unit" >&2; exit 2; }
awk '
  { s = $2; key = $3; if ($4 != "") key = key " " $4; if ($5 != "") key = key " " $5
    sum[key] += s; cnt[key]++ }
  END { for (k in sum) { w = int(sum[k] / cnt[k] + 0.5); if (w < 1) w = 1; print w, k } }
' "$tmp" | sort -k1,1nr -k2 > "$tmp.out"
units=$(wc -l < "$tmp.out" | tr -d ' ')
{
  echo '# Unit weights for tests/selftest.sh (A109): "<seconds> <suite> [scenario]", longest first.'
  echo "# Generated by tests/selftest-weights.sh from $nfiles times file(s), $units units; a unit seen in several files weighs the"
  echo '# average of its seconds. Seconds are as measured under a 4-core CI shard; only the ratios matter.'
  echo '# A unit that is not listed weighs the MEDIAN of the listed units. Shards are filled longest unit first onto the'
  echo '# lightest shard; a stale weight only costs balance, it never drops or loosens a test.'
  echo '# Refresh: download the selftest-times artifacts of a CI run, then sh tests/selftest-weights.sh <dir>.'
  [ -z "$notes" ] || printf '%s\n' "$notes" | sed '1{/^$/d;}'
  cat "$tmp.out"
} > "$tmp" && cat "$tmp" > "$out"
